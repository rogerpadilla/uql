export const PG_SQL_VALUES: SqlValues = { ...ANSI_SQL_VALUES, uuid: 'gen_random_uuid()' };

/** What Postgres and CockroachDB share: JSONB, full-text search, pgvector's operators, and the upsert. */
export abstract class PgLikeSqlDialect extends AbstractSqlDialect {
  /** Every member of this family runs the same SQL, so a body written once serves them all. */
  override get dialectFamily(): SqlDialectName {
    return 'postgres';
  }

  /** How the driver binds a parameter: node-`pg`'s, unless the pool states its own. */
  readonly driverCapabilities: DriverCapabilities;

  constructor(options: PgLikeDialectOptions = {}) {
    super(options);
    this.driverCapabilities = { nativeArrays: true, explicitJsonCast: false, ...options.driverCapabilities };
  }

  override readonly features: SqlDialectFeatures = PG_FEATURES;

  override readonly sqlValues: SqlValues = PG_SQL_VALUES;

  /** `USING MESSAGE`, so the text is taken as it is rather than as a format reading each `%`. */
  protected override refusal(message: string): string {
    return `RAISE EXCEPTION USING MESSAGE = ${message};`;
  }

  override readonly escapeIdChar = '"';
  // Shared default for both dialects. CockroachDB docs flag sequential PKs as a hotspotting risk
  // under heavy concurrent insert load (writes concentrate on one range); this default still beats
  // `SERIAL` (CockroachDB's `unique_rowid()`, a ~64-bit value that overflows JS's safe-integer
  // range). High-throughput CockroachDB users should override this per-entity with a UUID PK.
  override readonly autoIncrementSuffix: string = 'GENERATED BY DEFAULT AS IDENTITY';

  /**
   * `JSON_AGG` of each row whole, read through a LATERAL projection of the columns it answers under:
   * the sort terms carried out beside them order it without joining the object, and no function call
   * builds it, so a wide row meets no argument limit. `json` has no equality, so under a parent's
   * `DISTINCT` the array is compared as `jsonb`.
   */
  protected override appendRelationArray(ctx: QueryContext, rows: RelationRows): readonly SelectTerm[] {
    const { terms, from, pairs, order } = this.derivedRelation(ctx, rows);
    const row = this.escapeId(RELATION_ROW_ALIAS, true);
    const columns = pairs.map(([, column]) => column).join(', ');
    const array = /*sql*/ `(SELECT COALESCE(JSON_AGG(${row}${order ? ` ORDER BY ${order}` : ''}), '[]'::json) FROM ${from} CROSS JOIN LATERAL (SELECT ${columns}) ${row})`;
    ctx.append(rows.distinct ? `${array}::jsonb` : array);
    return terms;
  }

  /**
   * Every Postgres-wire pool hands back a `BOOLEAN`, a date and an integer column decoded (an `INT8` by the
   * pools' own wide-number rule); a `NUMERIC`, a float and anything crossing JSON still decode as the base says.
   */
  protected override decodedAtWire(kind: HydrateKind, field: FieldOptions | undefined): boolean {
    return kind === 'boolean' || kind === 'date' || (kind === 'number' && !!field && isIntegerColumn(field));
  }

  /**
   * What JSON would round or cannot spell crosses it as text, for the field's own decode to read back:
   * a column declared numeric, whatever it decodes as, a vector, and bytes as hex.
   */
  protected override readonly carriedFields = {
    numeric: (expr) => `${expr}::text`,
    vector: (expr) => `${expr}::text`,
    blob: (expr) => `${this.escape(BYTES_PREFIX)} || ENCODE(${expr}, 'hex')`,
  } satisfies CarriedFields;

  /** A typed column as text, which a JSON path's text compares with: Postgres converts neither side of `text = uuid`. */
  protected override textOperand(column: string): string {
    return `${column}::text`;
  }

  override readonly maxBindValues: number = 65535;

  override readonly vectorMetrics = PG_VECTOR_METRICS;

  /**
   * The setting each vector index type reads for "how much of the index to explore". They are not the
   * same quantity - `ef_search` is a candidate-list size, `probes` a count of lists - which is why
   * `$candidates` is documented in the index's own units rather than as a portable number.
   */
  protected readonly annSettings: ReadonlyMap<IndexType, string> = new Map<IndexType, string>([
    ['hnsw', HNSW_EF_SEARCH],
    ['ivfflat', 'ivfflat.probes'],
  ]);

  /**
   * `SET LOCAL hnsw.ef_search = N`, plus `hnsw.iterative_scan = strict_order` where the query also filters
   * by distance, which would otherwise drop rows the candidate list missed.
   */
  override vectorTuningStatements<E>(meta: EntityMeta<E>, q: Query<E>): readonly string[] {
    const indexType = this.tunedVectorIndex(meta, q)?.type;
    const setting = indexType ? this.annSettings.get(indexType) : undefined;
    if (!setting) {
      return [];
    }
    const statements = [`SET LOCAL ${setting} = ${q.$candidates}`];
    if (setting === HNSW_EF_SEARCH && hasVectorNear(q.$where)) {
      statements.push('SET LOCAL hnsw.iterative_scan = strict_order');
    }
    return statements;
  }

  /** Binds a date as UTC text, which a zoneless `TIMESTAMP` stores as is, instead of each driver picking a zone. */
  protected override readonly dateZone = PG_UTC;

  override normalizeValue(value: unknown): unknown {
    if (Array.isArray(value)) {
      const values = value.map((item) => super.normalizeValue(item));
      return this.driverCapabilities.nativeArrays ? values : toPgArray(values);
    }
    return super.normalizeValue(value);
  }

  override placeholder(index: number): string {
    return `$${index}`;
  }

  /**
   * `<document> @@ WEBSEARCH_TO_TSQUERY(...)`, under the `$config` asked for, else that of the fulltext
   * index over these fields, which the planner serves it from. `WEBSEARCH_TO_TSQUERY` takes free-form
   * input (quoted phrases, `or`, `-negation`) and never raises a syntax error, unlike `TO_TSQUERY`.
   */
  protected override appendTextSearch<E>(
    ctx: QueryContext,
    meta: EntityMeta<E>,
    search: QueryTextSearchOptions<E>,
    prefix: string | undefined,
  ): void {
    const { document, query } = this.textSearchParts(meta, search, prefix);
    ctx.append(`${document} @@ ${query}`);
    ctx.addValue(search.$value);
    ctx.append(')');
  }

  /** `TS_RANK` of the document over `keys` against the same search the match reads. */
  protected override appendTextScore<E>(
    ctx: QueryContext,
    meta: EntityMeta<E>,
    search: QueryTextSearchOptions<E>,
    keys: readonly string[],
    prefix: string | undefined,
  ): void {
    const { document, query } = this.textSearchParts(meta, search, prefix, keys);
    ctx.append(`TS_RANK(${document}, ${query}`);
    ctx.addValue(search.$value);
    ctx.append('))');
  }

  /**
   * The document over `keys` and the search itself, open for its value, under the `$config` asked for,
   * else that of the fulltext index over every field searched, which is what serves the match.
   */
  private textSearchParts<E>(
    meta: EntityMeta<E>,
    search: QueryTextSearchOptions<E>,
    prefix: string | undefined,
    keys?: readonly string[],
  ): { document: string; query: string } {
    const fields = textSearchFields(meta, search);
    const index = fulltextIndexOver(meta, fields);
    const config = search.$config ?? (index && fulltextConfig(index));
    return {
      document: this.textSearchTarget(this.textColumns(meta, keys ?? fields, prefix), config),
      query: `${this.textQueryFn}(${this.textConfigArg(config)}`,
    };
  }

  /**
   * The document, `TO_TSVECTOR('english'::regconfig, COALESCE("a", '') || ' ' || COALESCE("b", ''))`, a
   * `NULL` column read as empty rather than emptying it all. The config is a literal: an index is built
   * over one, and a bound one reaches it only where the driver leaves the parameter untyped.
   */
  override textSearchTarget(columns: readonly string[], config?: string): string {
    const document = columns.map((column) => `COALESCE(${column}, '')`).join(` || ' ' || `);
    return `TO_TSVECTOR(${this.textConfigArg(config)}${document})`;
  }

  /** A config as the text-search functions' first argument, or nothing, for the server's default. */
  private textConfigArg(config: string | undefined): string {
    return config === undefined ? '' : `${this.escape(config)}${this.textConfigCast}, `;
  }

  /** How a config literal is typed, and the function reading a search's text: CockroachDB lacks both of these. */
  protected readonly textConfigCast: string = '::regconfig';
  protected readonly textQueryFn: string = 'WEBSEARCH_TO_TSQUERY';

  protected override jsonContains(ctx: QueryContext, slot: JsonSlot, values: readonly unknown[]): string {
    return `${this.jsonValue(slot)} @> ${this.jsonVal(ctx, values)}`;
  }

  protected override jsonLength(slot: JsonSlot): string {
    return `JSONB_ARRAY_LENGTH(${this.jsonArray(slot)})`;
  }

  /** Each element stays `jsonb`, so it is read as any path is: `->` for the value, `->>` for its text. */
  protected override jsonElemFrom(slot: JsonSlot, alias: string): string {
    return `JSONB_ARRAY_ELEMENTS(${this.jsonArray(slot)}) AS ${alias}`;
  }

  protected override jsonIs(slot: JsonSlot, kind: JsonContainer): string {
    return `JSONB_TYPEOF(${this.jsonValue(slot)}) = '${kind}'`;
  }

  protected override jsonIsNull(slot: JsonSlot): string {
    return `COALESCE(JSONB_TYPEOF(${this.jsonValue(slot)}), 'null') = 'null'`;
  }

  /** The array at `slot`, NULL where the value there is none: the array functions fail the whole read on one. */
  private jsonArray(slot: JsonSlot): string {
    return `CASE WHEN ${this.jsonIs(slot, 'array')} THEN ${this.jsonValue(slot)} END`;
  }

  protected override jsonElemDoc(alias: string): string {
    return alias;
  }

  /** `->` down the path and `->>` for its text, the document's own text being `#>> '{}'`. */
  protected override jsonPathReading(escapedColumn: string, path: string, mode: 'json' | 'text'): string {
    if (!path) {
      return mode === 'json' ? escapedColumn : `(${escapedColumn} #>> '{}')`;
    }
    const keys = jsonPathKeys(path);
    return keys.reduce((expr, key, index) => {
      const op = mode === 'text' && index === keys.length - 1 ? '->>' : '->';
      return `(${expr}${op}'${key}')`;
    }, escapedColumn);
  }

  /** A number only where the value is one: the cast throws on any other text, failing the whole read. */
  override jsonPathExpr(escapedColumn: string, path: string, mode: JsonAccessMode): string {
    const read = super.jsonPathExpr(escapedColumn, path, mode);
    if (mode !== 'numeric') {
      return read;
    }
    return `CASE WHEN JSONB_TYPEOF(${this.jsonValue({ base: escapedColumn, path })}) = 'number' THEN ${read} END`;
  }

  protected override regexCondition(operand: string, placeholder: string): string {
    return `${operand} ~ ${placeholder}`;
  }

  protected override readonly caseInsensitiveMatch = 'ilike';

  override neExpr(field: string, ph: string): string {
    return `${field} IS DISTINCT FROM ${ph}`;
  }

  /** A single key's list binds as one array, whatever its length. */
  override keyListCapacity(keyCount: number): number {
    return keyCount > 1 ? super.keyListCapacity(keyCount) : Infinity;
  }

  /**
   * One array parameter, which a context that inlines values has none of, nor a list holding SQL: those list them
   * instead. The array takes its type from `operand`, so it needs none of the casts `bind` gives each value.
   */
  protected override formatIn(
    ctx: QueryContext,
    operand: string,
    values: unknown[],
    negate: boolean,
    bind: (value: unknown) => string,
  ): string {
    if (!values.length || ctx.inlineValues || values.some((value) => value instanceof QuerySql)) {
      return super.formatIn(ctx, operand, values, negate, bind);
    }
    const ph = this.addValue(ctx, values);
    return negate ? `${operand} <> ALL(${ph})` : `${operand} = ANY(${ph})`;
  }

  override escape(value: unknown): string {
    return escapePgSqlLiteral(value);
  }

  protected override numericCast(expr: string): string {
    return `(${expr})::numeric`;
  }

  protected override appendJsonValue(ctx: QueryContext, value: unknown, type: JsonColumnType): void {
    ctx.append(this.jsonVal(ctx, value, type));
  }

  /**
   * pgvector needs the cast to pick the right type, and `sparsevec` needs its own literal: the dense
   * `[1,0,2]` every other type takes is rejected as "invalid input syntax for type sparsevec".
   */
  protected override appendVectorValue(ctx: QueryContext, value: readonly unknown[], field?: FieldOptions): void {
    const vectorType = this.supportedVectorType(resolveVectorCast(field));
    ctx.addValue(vectorType === 'sparsevec' ? toSparsevecLiteral(value) : `[${value.join(',')}]`);
    ctx.append(`::${vectorType}`);
  }

  /** `WITH ORDINALITY` numbers each element, which the aggregate orders by to keep the survivors in their order. */
  protected override jsonKeptFrom(slot: JsonSlot): string {
    return `JSONB_ARRAY_ELEMENTS(${this.jsonValue(slot)}) WITH ORDINALITY AS ${JSON_PULL_ALIAS}(${JSON_PULL_ALIAS}, ord)`;
  }

  protected override jsonKeptAggregate(): string {
    return `JSONB_AGG(${JSON_PULL_ALIAS} ORDER BY ${JSON_PULL_ALIAS}.ord)`;
  }

  /** Each key or dotted path set as `jsonb`, which `JSONB_SET` takes and nothing else. */
  protected override jsonSet(ctx: QueryContext, expr: string, set: Record<string, unknown>): string {
    return Object.entries(set).reduce(
      (acc, [path, value]) => this.jsonSetKey(acc, path, this.jsonbOf(ctx, value)),
      expr,
    );
  }

  /**
   * A value as `jsonb` inside a document: a null one JSON's, as `JSONB_SET` and a comparison need, and a `sql()`
   * one read back out of an object, since `TO_JSONB` refuses an untyped literal.
   */
  private jsonbOf(ctx: QueryContext, value: unknown): string {
    if (value instanceof QuerySql) {
      return `JSONB_BUILD_OBJECT('v', ${this.rawFragment(ctx, value)})->'v'`;
    }
    return value === null ? `'null'::jsonb` : this.jsonVal(ctx, value);
  }

  /** `JSONB_BUILD_ARRAY` takes any type, and a NULL as JSON's null. */
  protected override jsonAppended(ctx: QueryContext, array: string, value: unknown, unless?: string): string {
    return `${array} || ${unlessThen(unless, this.jsonEmptyArray, `JSONB_BUILD_ARRAY(${this.jsonVal(ctx, value)})`)}`;
  }

  protected override readonly jsonEmptyObject = `'{}'::jsonb`;

  protected override readonly jsonEmptyArray = `'[]'::jsonb`;

  /** `JSONB_SET` takes one path, so each key wraps the last. */
  protected override jsonWriteKeys(
    expr: string,
    writes: readonly JsonKeyWrite[],
    { create }: { create: boolean },
  ): string {
    return writes.reduce(
      (acc, [slot, value]) => this.jsonSetKey(acc, slot.path, this.jsonOrStored(slot, value), { create }),
      expr,
    );
  }

  /** A replace hands an absent key's NULL back, which `JSONB_SET` would answer for the whole document. */
  private jsonSetKey(expr: string, path: string, value: string, { create = true } = {}): string {
    const set = create ? value : `COALESCE(${value}, 'null'::jsonb), false`;
    return `JSONB_SET(${expr}, '${toPgArray(jsonPathKeys(path))}', ${set})`;
  }

  protected override jsonUnset(ctx: QueryContext, expr: string, unset: readonly string[]): string {
    return unset.reduce((acc, path) => `(${acc}) #- '${toPgArray(jsonPathKeys(path))}'`, expr);
  }

  /** Postgres binds JSON with a numbered placeholder and an explicit cast, per driver capability. */
  protected override jsonScalarParam(ctx: QueryContext, value: unknown): string {
    return this.jsonbOf(ctx, value);
  }

  /**
   * Helper to add a JSON value to context with appropriate stringification and cast.
   */
  private jsonVal(ctx: QueryContext, value: unknown, type: JsonColumnType = 'jsonb'): string {
    if (value instanceof QuerySql) return this.rawFragment(ctx, value);
    if (value == null) return `${this.addValue(ctx, null)}::${type}`;

    const json = JSON.stringify(value);
    const ph = this.addValue(ctx, json);
    return this.driverCapabilities.explicitJsonCast ? `(${ph}::text)::${type}` : `${ph}::${type}`;
  }
}

/**
 * Converts a JS array to a Postgres array literal string: `{"val1","val2"}`.
 * Safely handles nesting and escaping of special characters.
 */
function toPgArray(arr: unknown[]): string {
  const elements = arr.map((val) => {
    if (val == null) return 'NULL';
    if (Array.isArray(val)) return toPgArray(val);
    if (typeof val === 'boolean') return val ? 'true' : 'false';
    // A Node `Buffer` is a `Uint8Array` too.
    if (val instanceof Uint8Array) {
      return `"\\\\x${bytesToHex(val)}"`;
    }
    const str = String(val);
    const escaped = str.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    return `"${escaped}"`;
  });
  return `{${elements.join(',')}}`;
}
